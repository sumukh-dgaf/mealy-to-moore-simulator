/**
 * Build TestCases/test_cases.md from the records of a real test run.
 *
 *   TEST_RESULTS=core_results.json node --test                     (records of tests/core.test.js)
 *   PLAYWRIGHT=… node tests/ui-check.js http://localhost:8000/ <dir> (writes <dir>/ui_results.json)
 *   node tests/make-test-table.js core_results.json [ui_results.json] > test_cases.md
 *
 * Every "Actual result" and "Status" cell is copied from those records; nothing is typed by hand.
 */
const fs = require('node:fs');

const [coreFile, uiFile] = process.argv.slice(2);
if (!coreFile) {
  console.error('usage: node tests/make-test-table.js <core_results.json> [ui_results.json]');
  process.exit(2);
}
const core = JSON.parse(fs.readFileSync(coreFile, 'utf8'));
const ui = uiFile ? JSON.parse(fs.readFileSync(uiFile, 'utf8')) : [];
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const pass = (rs) => rs.filter((r) => r.status === 'Pass').length;
const out = [];

out.push('# Test cases: Mealy → Moore Conversion Simulator (Milestone 2)', '');
out.push(`Generated by \`tests/make-test-table.js\` from the records of the actual run on ${new Date().toISOString().slice(0, 10)}.`);
out.push(`Unit and property tests (\`node --test\`): **${pass(core)} of ${core.length} checks passed**. ` +
  (ui.length ? `Scripted UI checks (Playwright, \`tests/ui-check.js\`): **${pass(ui)} of ${ui.length} passed**.` : 'UI checks were not run.'));
out.push('', 'Full console output of both runs: `test_log.txt`. Machine definitions: the JSON files in this folder.', '');

out.push('## 1. Unit, property and performance tests (`tests/core.test.js`)', '');
out.push('| Test ID | Feature/input | Expected result | Actual result | Status (Pass/Fail) |', '|---|---|---|---|---|');
for (const r of core) {
  out.push(`| ${r.id} | ${cell(`${r.feature}. Machine: ${r.machine}. Input: ${r.input}`)} | ${cell(r.expected)} | ${cell(r.actual + (r.detail ? ` (${r.detail})` : ''))} | ${r.status} |`);
}
if (ui.length) {
  out.push('', '## 2. Scripted UI checks on the running simulator (`tests/ui-check.js`)', '');
  out.push('| Test ID | Feature/input | Expected result | Actual result | Status (Pass/Fail) |', '|---|---|---|---|---|');
  for (const r of ui) {
    out.push(`| ${r.id} | ${cell(`${r.feature}. Input: ${r.input}`)} | ${cell(r.expected)} | ${cell(r.actual + (r.detail ? ` (${r.detail})` : ''))} | ${r.status} |`);
  }
}

out.push('', '## 3. Category and evidence for each check', '');
out.push('| Test ID | Category | Evidence |', '|---|---|---|');
for (const r of core) out.push(`| ${r.id} | ${r.category} | ${cell(r.evidence || `test_log.txt, line "${r.id} observed"`)} |`);
for (const r of ui) out.push(`| ${r.id} | UI check | ${cell(r.evidence)} |`);

// README "Supported features" → the checks that cover each one (status computed from the run).
const FEATURES = [
  ['Mealy machine editor with two built-in examples', ['UI-01', 'UI-08']],
  ['Import of transition-table text or JSON', ['TC-25a', 'TC-19a', 'TC-19b', 'TC-19c', 'UI-10']],
  ['Input validation with a message for every error', ['TC-13a', 'TC-13b', 'TC-14a', 'TC-14b', 'TC-15', 'TC-16a', 'TC-16b', 'TC-17a', 'TC-17b', 'TC-17c', 'TC-18', 'TC-20', 'UI-08', 'UI-09']],
  ['Mealy → Moore conversion by state splitting (Algorithm A) with its options', ['TC-01', 'TC-02a', 'TC-02b', 'TC-02c', 'TC-03a', 'TC-03b', 'TC-04a', 'TC-04b', 'TC-05a', 'TC-05b', 'TC-06a', 'TC-06b', 'TC-07', 'TC-09', 'TC-10', 'TC-22']],
  ['Step-by-step player', ['TC-23', 'UI-02', 'UI-07']],
  ['SVG state diagrams and transition tables (larger machines scroll)', ['UI-03', 'UI-15']],
  ['String tester on both machines, including ε and random strings', ['TC-08a', 'TC-08b', 'TC-12', 'TC-24a', 'UI-04', 'UI-04b']],
  ['Exact equivalence check (Algorithm C) and check of a hand-converted Moore machine', ['TC-11', 'TC-24b', 'UI-05', 'UI-06']],
  ['Export of the diagram (SVG / PNG)', ['UI-11']],
  ['Export of the generated Moore machine (JSON / table text)', ['TC-25b', 'UI-12']],
  ['Share link', ['UI-13']],
  ['Project design tab', ['UI-16']],
  ['Runs offline from file://; no sideways scrolling at 1200–1366 px', ['UI-17', 'UI-14']],
  ['Console front-end', ['TC-26', 'TC-26b']],
  ['Performance', ['TC-21']],
  ['Solve from a question (AI reads the question; mocked API in tests)', ['TC-27', 'TC-28', 'TC-29a', 'TC-29b', 'TC-29c', 'TC-30a', 'TC-30b', 'TC-31', 'TC-34', 'TC-35', 'TC-36', 'UI-19', 'UI-20', 'UI-21', 'UI-22', 'UI-25', 'UI-26', 'UI-27', 'UI-28', 'UI-29', 'UI-30', 'UI-31']],
  ['Explanation in words, Moore state names and Copy answer', ['TC-32a', 'TC-32b', 'TC-32c', 'TC-33', 'UI-23', 'UI-24']],
];
const GUIDE = [
  ['Empty string ε: Mealy ε, Moore λ′(q0′), first symbol dropped → ε', ['TC-08a', 'TC-08b']],
  ['Unknown input symbol → validation error', ['TC-14a', 'TC-24a']],
  ['Unknown output symbol → validation error', ['TC-14b']],
  ['Missing transition / malformed definition → documented rules', ['TC-13a', 'TC-13b', 'TC-19a', 'TC-19b', 'TC-19c']],
  ['Duplicate transition (non-determinism) → validation error', ['TC-15']],
  ['State with no incoming transitions → [q,−] with the default output', ['TC-04a', 'TC-04b']],
  ['Unreachable states → removed', ['TC-06a', 'TC-06b', 'UI-07']],
  ['Bound |Q′| ≤ |Q|·|Δ|, including a case that reaches it exactly', ['TC-10', 'TC-07', 'TC-22']],
  ['Wrong hand-converted Moore machine → shortest counterexample', ['TC-11', 'UI-06']],
  ['Random-string agreement', ['TC-12', 'UI-04b']],
];
const all = new Map([...core, ...ui].map((r) => [r.id, r.status]));
const coverage = (rows, title, head) => {
  out.push('', title, '', `| ${head} | Tests | Result |`, '|---|---|---|');
  for (const [name, ids] of rows) {
    const missing = ids.filter((id) => !all.has(id));
    const ran = ids.filter((id) => all.has(id));
    const result = missing.length ? `not run: ${missing.join(', ')}` : `${ran.filter((id) => all.get(id) === 'Pass').length}/${ran.length} pass`;
    out.push(`| ${cell(name)} | ${ids.join(', ')} | ${result} |`);
  }
};
coverage(FEATURES, '## 4. Coverage of the README feature list', 'README feature');
coverage(GUIDE, '## 5. Coverage of the required edge cases (M2 brief, adapted from the guide\'s T01–T05 template)', 'Required case');

out.push('', '## 6. Numbering and adaptations', '');
out.push('- The final M1 test plan (docs/milestone1/M1_Design_Document.md §14) lists TC-01 … TC-21; all 21 are automated here with the same IDs. ' +
  'TC-22 … TC-26 are new in M2 so that every README feature has a test. A letter suffix (TC-14a, TC-14b) marks separate checks inside one test.');
out.push('- TC-02 planned "classic textbook machines from course material". No course-material answers were available to compare with, so three ' +
  'classic machines (complementer, running parity, overlapping 101 detector) were converted by hand and the program is checked against those hand results.');
out.push('- TC-12 planned 500 random strings; it runs 500 seeded strings on each of 7 machines (3,500 comparisons). TC-21 reports the median of 5 timed runs.');
out.push('- TC-13 (missing transition): the simulator rejects incomplete machines with one error per missing (state, symbol) pair. It never adds a trap state.');
out.push('- TC-27 … TC-36 and UI-19 … UI-31 test "Solve from a question". They use hand-written model replies in the response-schema format (tests/fixtures/ai/) and, in the UI checks, a mocked Gemini API (Playwright route interception). No live API call is made by the tests.');
out.push('- Cross-checks are against hand-worked traces only (TC-01, TC-02a–c, TC-03a–b, TC-07, TC-09, TC-10, TC-11). No JFLAP cross-check was done.');

fs.writeSync(1, out.join('\n') + '\n');
